import { handler, generateImage, imagePart } from '../../lib/gemini.js';

const POSE = {
  tops: 'ゴーストマネキン（見えないマネキンに着せた立体感）で真正面から。肩・袖・身頃が左右対称で、襟はきれいに整えて立ち上がっている',
  outer: 'ゴーストマネキン（見えないマネキンに着せた立体感）で真正面から。前は閉じ、ラペル・襟・ポケットフラップがきれいに整い、左右対称',
  bottoms: '真正面から、プレスラインの通った状態でまっすぐ。左右の脚が対称に揃っている',
  shoes: '片方を真横（外側）から、もう片方をその少し後ろに斜めに並べた、ブランド公式サイト定番の構図',
  bag: '真正面から自立させ、形がきれいに張った状態。持ち手は自然に立てる',
  accessory: '真正面または真上から。小さいものは画面いっぱいに大きく、質感がはっきり分かるように',
  other: '真正面から',
};

// 写真（ハンガー・床・シワがあってもOK）→ 公式ブランドのオンラインブティックの単品写真
export const onRequestPost = handler(async (body, env) => {
  const { image, name = '', category = 'other', brand = '' } = body;
  const { image: out, model } = await generateImage(env, {
    parts: [
      imagePart(image),
      {
        text: `この写真の${brand ? `${brand}の` : ''}「${name || 'アイテム'}」を、ハイブランドの公式オンラインブティックに載っている単品の商品写真として1枚生成して。

## 仕上がり
- 新品の状態：シワ・ヨレ・たるみ・毛玉・ホコリ・色あせは一切なし。アイロンでプレスしたようにパリッと整っている
- 形：左右対称で、本来のシルエットが一番きれいに見える状態
- 構図：${POSE[category] || POSE.other}
- ライティング：スタジオのソフトボックスで均一。素材の質感（織り・起毛・革の艶など）が分かる高精細な描写。色は正確に
- 背景：完全な純白(#FFFFFF)の無地。影・反射・床・グラデーションは一切なし（あとで背景を透過するため）
- 被写体だけを中央に、上下左右に少し余白

## 絶対に守ること
- 写さない：ハンガー、タグ、値札、人の体や手、床、家具、他の服や物
- 色・柄・素材・ロゴ・ボタン・ステッチ・ポケット・金具などのデザインは元の写真と同じにする。シワやヨレ以外は変えない。装飾を足さない
- 隠れて見えない部分は、見えている部分から自然に補完する`,
      },
    ],
  });
  return { image: out, model };
});
